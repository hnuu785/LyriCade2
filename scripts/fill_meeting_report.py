def get_paragraph_after(doc: Document, heading: str):
    for idx, paragraph in enumerate(doc.paragraphs):
        if paragraph.text.strip() == heading:
            return doc.paragraphs[idx + 1]
    raise ValueError(f"Heading not found: {heading}")


def replace_paragraph_with_lines(doc: Document, heading: str, lines: list[str]) -> None:
    paragraph = get_paragraph_after(doc, heading)
    if not lines:
        paragraph.text = ""
        return

    paragraph.text = lines[-1]
    for line in reversed(lines[:-1]):
        paragraph.insert_paragraph_before(line)


